/// Writes when `YANTRA_FIXTURES` is set and compares otherwise, so the
/// committed file cannot fall behind the routes without something going red.
#[tokio::test]
async fn the_dashboard_reads_what_the_daemon_writes() {
    let path = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join(GENERATED);
    let rendered = render(answers().await);

    if std::env::var_os("YANTRA_FIXTURES").is_some() {
        std::fs::write(&path, &rendered).expect("the web directory is in the same checkout");
        return;
    }

    let committed = std::fs::read_to_string(&path).expect("the fixture is committed");
    assert!(
        committed == rendered,
        "web/src/contract.gen.ts no longer matches what /api answers — run `just fixtures`"
    );
}

/// Each answer beside the `web/src/api.ts` type it must satisfy. Those type
/// names are the whole of what this file restates about TypeScript.
async fn answers() -> Vec<(&'static str, &'static str, Value)> {
    let fleet = fleet().await;
    let mut out = vec![
        (
            "machines",
            "Looked<Machine[]>",
            read(&fleet, "/machines").await,
        ),
        (
            "workspaces",
            "Looked<Listed[]>",
            read(&fleet, "/workspaces").await,
        ),
        (
            "sessions",
            "Looked<MachineSessions[]>",
            read(&fleet, "/sessions").await,
        ),
        (
            "agents",
            "Looked<WorkspaceStatus>[]",
            Value::Array(agents(&fleet).await),
        ),
        (
            "readiness",
            "Looked<Readiness[]>",
            read(&fleet, "/readiness").await,
        ),
        (
            "oneReadiness",
            "Looked<Readiness>",
            read(&fleet, "/machines/cachyos-g14/readiness").await,
        ),
        (
            "attention",
            "Looked<Attention>",
            read(&fleet, "/attention").await,
        ),
        (
            "notLooked",
            "Looked<Machine[]>",
            read(&Fleet::default(), "/machines").await,
        ),
        (
            "failed",
            "Looked<Machine[]>",
            read(&broken(), "/machines").await,
        ),
    ];
    out.extend(crate::write::answers());
    out.extend(crate::terminal::answers());
    out
}

async fn read(fleet: &Fleet, path: &str) -> Value {
    let response = crate::api::router()
        .with_state(fleet.clone())
        .oneshot(
            Request::get(path)
                .body(Body::empty())
                .expect("a GET with no body is a valid request"),
        )
        .await
        .expect("the router is infallible");
    let body = axum::body::to_bytes(response.into_body(), 64 * 1024)
        .await
        .expect("the body is in memory");
    serde_json::from_slice(&body).expect("every answer is JSON")
}

/// One request per verdict, because `columns.tsx` switches on all nine — a
/// state that only ever appears in a hand-written stub is a state nothing
/// checks — and one for a machine that did not answer.
async fn agents(fleet: &Fleet) -> Vec<Value> {
    let mut out = Vec::new();
    for (name, _) in verdicts() {
        out.push(read(fleet, &format!("/workspaces/{name}/status")).await);
    }
    out.push(read(fleet, "/workspaces/unreachable/status").await);
    out
}

