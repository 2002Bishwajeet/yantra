//! The daemon-to-browser seam, checked rather than trusted (Y-124).
//!
//! [`api`](crate::api)'s DTOs and `web/src/api.ts` describe one wire shape in
//! two languages and nothing compared them: renaming a field here left every
//! Rust and TypeScript test green and the dashboard blank. So the real routes
//! render the fixture below and it is committed as TypeScript that `satisfies`
//! the types the dashboard reads with. A rename fails **here** first, because
//! the committed file stops matching what the routes now answer, and fails
//! `tsc` second, once someone regenerates it without moving `api.ts`.
//!
//! **TypeScript rather than JSON.** An imported JSON module has its string
//! literals widened to `string`, which no discriminated union accepts, so the
//! assertion has to sit where the literal is written.
//!
//! The write answers are serialised from their DTOs rather than fetched from
//! the router: those handlers `await` ssh and authorise a real tailnet caller,
//! neither of which a unit test has.
//!
//! `terminalSize` is the first entry travelling the other way — a shape the
//! *browser* writes and the daemon reads (Y-129). `satisfies` checks the same
//! thing about it, which is that the two sides spell one message identically;
//! that the daemon then accepts it is [`crate::terminal`]'s own test.

