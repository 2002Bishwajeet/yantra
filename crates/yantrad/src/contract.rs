fn render(answers: Vec<(&str, &str, Value)>) -> String {
    let mut out = HEADER.to_owned();
    for (name, ts, value) in answers {
        let json = serde_json::to_string_pretty(&value).expect("a rendered answer is JSON");
        out.push_str(&format!("\nexport const {name} = {json} satisfies {ts}\n"));
    }
    out
}
