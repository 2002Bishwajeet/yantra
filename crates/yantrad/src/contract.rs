/// The look itself failing is the fourth state, and it is the one a page draws
/// as an empty fleet if the envelope ever stops naming it.
fn broken() -> Fleet {
    holding(Snapshot {
        machines: Some(Arc::new(Reading::new(Err(
            yantra_core::inventory::Error::Command {
                stderr: "failed to connect to local tailscaled".into(),
            },
        )))),
        ..Snapshot::default()
    })
}

fn holding(snapshot: Snapshot) -> Fleet {
    Fleet {
        model: Arc::new(tokio::sync::RwLock::new(snapshot)),
        beats: Beats::default(),
        ..Fleet::default()
    }
}

